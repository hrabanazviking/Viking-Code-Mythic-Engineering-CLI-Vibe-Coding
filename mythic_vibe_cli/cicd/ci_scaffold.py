def _render_unknown(stack: DetectedStack) -> str:
    return f"""# Generated by `mythic-vibe ci scaffold` (PH-12 Slice 12.1).
# Stack detection inconclusive (no recognised manifest).
# Detected languages: {list(stack.detected_languages) or 'none'}.
#
# Hand-tune the steps below for your project's tooling.

name: CI

on:
  push:
    branches: [main, development]
  pull_request:
    branches: [main, development]

jobs:
  test:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - name: TODO — install your dependencies here
        run: echo "no install configured"
      - name: TODO — run your tests here
        run: echo "no tests configured"
"""


def render_ci_workflow(stack: DetectedStack) -> str:
    """Pick the right per-language template for ``stack``. Falls
    back to a TODO scaffold when nothing is recognised."""
    primary = stack.primary_language
    if primary == "python":
        return _render_python(stack)
    if primary == "node":
        return _render_node(stack)
    if primary == "rust":
        return _render_rust()
    if primary == "go":
        return _render_go()
    return _render_unknown(stack)


# ---- Orchestration ---------------------------------------------------


def scaffold_ci_workflow(
    root: Path,
    *,
    force: bool = False,
    dry_run: bool = False,
) -> CIScaffoldResult:
    """Detect the stack and (unless ``dry_run``) write the
    workflow YAML. ``force`` overwrites an existing file;
    otherwise the existing file is left in place and the result
    captures the conflict in ``skipped_reason``."""
    stack = detect_stack(root)
    body = render_ci_workflow(stack)
    target = Path(root) / CI_WORKFLOW_PATH

    result = CIScaffoldResult(target=target, body=body, stack=stack)

    if dry_run:
        result.notes.append("dry-run; no file written")
        return result

    if target.is_file() and not force:
        result.skipped_reason = (
            f"{target} already exists. Re-run with --force to overwrite."
        )
        return result

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(body, encoding="utf-8")
    result.written = True
    return result


